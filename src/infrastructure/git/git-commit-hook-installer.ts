import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join, normalize, relative, sep } from 'node:path';
import type { InstallPlan } from '../../application/ports/file-change.js';
import type { CommitHookInstaller } from '../../application/ports/commit-hook-installer.js';

export const BLOCK_START = '# >>> estimetry >>>';
export const BLOCK_END = '# <<< estimetry <<<';
/**
 * Runs in the background, so the commit never waits, and stays silent for
 * colleagues without estimetry. The sha is taken first, in the hook itself:
 * by the time the background process looks, `HEAD` may already be the next commit.
 */
export const BLOCK_COMMAND =
  'if command -v estimetry >/dev/null 2>&1; then estimetry_sha=$(git rev-parse HEAD 2>/dev/null); printf \'%s\' "$estimetry_sha" | estimetry hook git post-commit >/dev/null 2>&1 & fi';
const BLOCK = [BLOCK_START, BLOCK_COMMAND, BLOCK_END];
const HUSKY_LOADER = '. "$(dirname "$0")/_/husky.sh"';
const SHELLS = /^#!.*\b(sh|bash|zsh|dash|ksh)\b/;
const MANAGERS: readonly (readonly [RegExp, string])[] = [
  [/lefthook/i, 'lefthook'],
  [/pre-commit\.com/, 'pre-commit'],
  [/husky/i, 'husky'],
];

/** `shown` is the path as the user sees it in messages: relative inside the project. */
type Layout = { readonly path: string; readonly shown: string; readonly husky?: 5 | 9 };

/** `post-commit` next to the hooks the repository already has: `core.hooksPath`, worktrees and husky. */
export class GitCommitHookInstaller implements CommitHookInstaller {
  installed(projectRoot: string): boolean {
    const layout = this.layout(projectRoot);
    return layout !== undefined && (read(layout.path) ?? '').includes(BLOCK_START);
  }

  plan(projectRoot: string, enabled: boolean): InstallPlan {
    const layout = this.layout(projectRoot);
    if (layout === undefined) {
      return enabled ? { changes: [], skipped: [], warnings: ['not a git repository, so --track-commits was skipped'] } : EMPTY;
    }
    const current = read(layout.path);
    return enabled ? this.install(layout, current) : this.uninstall(layout, current);
  }

  private install(layout: Layout, current: string | undefined): InstallPlan {
    const warnings: string[] = [];
    if (layout.husky !== undefined) {
      warnings.push(`${layout.shown} is part of the repository: the hook runs for colleagues who have estimetry installed`);
    }
    if (current === undefined) {
      const header = layout.husky === 9 ? [] : layout.husky === 5 ? ['#!/bin/sh', HUSKY_LOADER, ''] : ['#!/bin/sh'];
      return { changes: [{ path: layout.path, content: `${[...header, ...BLOCK].join('\n')}\n`, executable: true }], skipped: [], warnings };
    }
    const lines = current.split('\n');
    if (lines[0]?.startsWith('#!') && !SHELLS.test(lines[0])) {
      return {
        changes: [],
        skipped: [{ path: layout.path, reason: `not a shell script; add this line to it yourself: ${BLOCK_COMMAND}` }],
        warnings,
      };
    }
    const manager = layout.husky === undefined ? MANAGERS.find(([pattern]) => pattern.test(current))?.[1] : undefined;
    if (manager !== undefined) {
      warnings.push(`${layout.shown} is managed by ${manager}, which may drop the estimetry block when it reinstalls its hooks; run init again then`);
    }
    return { changes: [{ path: layout.path, content: withBlock(lines), executable: true }], skipped: [], warnings };
  }

  private uninstall(layout: Layout, current: string | undefined): InstallPlan {
    if (current === undefined || !current.includes(BLOCK_START)) {
      return EMPTY;
    }
    const rest = withoutBlock(current.split('\n'));
    const meaningful = rest.filter((line) => line.trim() !== '' && !line.startsWith('#!') && !line.includes('husky.sh'));
    return {
      changes: [meaningful.length === 0 ? { path: layout.path, remove: true } : { path: layout.path, content: rest.join('\n') }],
      skipped: [],
      warnings: [],
    };
  }

  /** Where `post-commit` goes, or undefined outside git. */
  private layout(projectRoot: string): Layout | undefined {
    const hooks = git(projectRoot, ['rev-parse', '--path-format=absolute', '--git-path', 'hooks']);
    if (hooks === undefined) {
      return undefined;
    }
    const configured = git(projectRoot, ['config', '--get', 'core.hooksPath']);
    const huskyDir = join(projectRoot, '.husky');
    if (configured !== undefined) {
      const path = normalize(configured).replace(/[\\/]+$/, '');
      // Files in .husky/_ are regenerated by husky 9; user hooks live one level up.
      if (path.endsWith(`.husky${sep}_`) || path === join('.husky', '_')) {
        return located(projectRoot, join(huskyDir, 'post-commit'), 9);
      }
      if (path === '.husky' || path.endsWith(`${sep}.husky`)) {
        return located(projectRoot, join(huskyDir, 'post-commit'), 5);
      }
    }
    return located(projectRoot, join(hooks, 'post-commit'));
  }
}

const EMPTY: InstallPlan = { changes: [], skipped: [], warnings: [] };

function located(projectRoot: string, path: string, husky?: 5 | 9): Layout {
  const inside = relative(projectRoot, path);
  const shown = inside !== '' && !inside.startsWith('..') ? inside : path;
  return husky === undefined ? { path, shown } : { path, shown, husky };
}

/** The block right after the shebang (and the husky loader), so an `exit` at the end cannot skip it. */
function withBlock(lines: readonly string[]): string {
  const rest = withoutBlock(lines);
  let at = rest[0]?.startsWith('#!') ? 1 : 0;
  if (rest[at]?.includes('husky.sh')) {
    at += 1;
  }
  return [...rest.slice(0, at), ...BLOCK, ...rest.slice(at)].join('\n');
}

function withoutBlock(lines: readonly string[]): string[] {
  const start = lines.indexOf(BLOCK_START);
  const end = lines.indexOf(BLOCK_END, start);
  return start === -1 || end === -1 ? [...lines] : [...lines.slice(0, start), ...lines.slice(end + 1)];
}

function read(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return undefined;
  }
}

function git(cwd: string, args: readonly string[]): string | undefined {
  try {
    const output = execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], windowsHide: true }).trim();
    return output === '' ? undefined : output;
  } catch {
    return undefined;
  }
}
