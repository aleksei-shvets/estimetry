import { execFileSync, spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readFileSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { isRemoval, type InstallPlan } from '../../src/application/ports/file-change.js';
import { NodeProjectFiles } from '../../src/infrastructure/fs/node-project-files.js';
import { BLOCK_COMMAND, GitCommitHookInstaller } from '../../src/infrastructure/git/git-commit-hook-installer.js';
import { tempDir } from '../support/temp-dir.js';

const installer = new GitCommitHookInstaller();
const files = new NodeProjectFiles();

function repo(): string {
  const dir = tempDir('repo-');
  execFileSync('git', ['init', '-q'], { cwd: dir });
  execFileSync('git', ['config', 'user.email', 'dev@example.com'], { cwd: dir });
  execFileSync('git', ['config', 'user.name', 'Dev'], { cwd: dir });
  return dir;
}

function apply(plan: InstallPlan): InstallPlan {
  for (const change of plan.changes) {
    if (isRemoval(change)) {
      files.remove(change.path);
    } else {
      files.write(change.path, change.content, change.executable ? { executable: true } : {});
    }
  }
  return plan;
}

const isExecutable = (path: string) => (statSync(path).mode & 0o111) !== 0;
const blocks = (text: string) => text.split('# >>> estimetry >>>').length - 1;

describe('GitCommitHookInstaller', () => {
  it('creates an executable hook in a plain repository, once', () => {
    const dir = repo();
    const hook = join(dir, '.git', 'hooks', 'post-commit');
    apply(installer.plan(dir, true));
    expect(readFileSync(hook, 'utf8')).toBe(`#!/bin/sh\n# >>> estimetry >>>\n${BLOCK_COMMAND}\n# <<< estimetry <<<\n`);
    expect(isExecutable(hook)).toBe(true);
    expect(installer.installed(dir)).toBe(true);
    const again = installer.plan(dir, true);
    expect(again.changes[0]).toMatchObject({ content: readFileSync(hook, 'utf8') });
  });

  it('follows core.hooksPath', () => {
    const dir = repo();
    execFileSync('git', ['config', 'core.hooksPath', 'tools/githooks'], { cwd: dir });
    apply(installer.plan(dir, true));
    expect(existsSync(join(dir, 'tools', 'githooks', 'post-commit'))).toBe(true);
  });

  it('uses the common hooks directory from a worktree', () => {
    const dir = repo();
    execFileSync('git', ['commit', '-q', '--allow-empty', '-m', 'init'], { cwd: dir });
    const worktree = join(tempDir('wt-'), 'feature');
    execFileSync('git', ['worktree', 'add', '-q', worktree], { cwd: dir });
    apply(installer.plan(worktree, true));
    expect(existsSync(join(dir, '.git', 'hooks', 'post-commit'))).toBe(true);
  });

  it('writes husky 9 hooks into .husky/post-commit without a shebang, with a warning', () => {
    const dir = repo();
    execFileSync('git', ['config', 'core.hooksPath', '.husky/_'], { cwd: dir });
    const plan = apply(installer.plan(dir, true));
    expect(readFileSync(join(dir, '.husky', 'post-commit'), 'utf8').startsWith('# >>> estimetry >>>')).toBe(true);
    expect(plan.warnings).toEqual(['.husky/post-commit is part of the repository: the hook runs for colleagues who have estimetry installed']);
  });

  it('writes husky 5–8 hooks with the husky loader', () => {
    const dir = repo();
    execFileSync('git', ['config', 'core.hooksPath', '.husky'], { cwd: dir });
    apply(installer.plan(dir, true));
    expect(readFileSync(join(dir, '.husky', 'post-commit'), 'utf8')).toMatch(/^#!\/bin\/sh\n\. "\$\(dirname "\$0"\)\/_\/husky\.sh"\n\n# >>> estimetry >>>/);
  });

  it('puts the block right after the shebang of an existing script and keeps the rest', () => {
    const dir = repo();
    const hook = join(dir, '.git', 'hooks', 'post-commit');
    writeFileSync(hook, '#!/bin/bash\n./notify.sh\nexit 0\n');
    apply(installer.plan(dir, true));
    const text = readFileSync(hook, 'utf8');
    expect(text).toMatch(/^#!\/bin\/bash\n# >>> estimetry >>>\n.*\n# <<< estimetry <<<\n\.\/notify\.sh\nexit 0\n$/);
    apply(installer.plan(dir, true));
    expect(blocks(readFileSync(hook, 'utf8'))).toBe(1);
    expect(isExecutable(hook)).toBe(true);
  });

  it('leaves a hook in another language alone and tells what to add', () => {
    const dir = repo();
    const hook = join(dir, '.git', 'hooks', 'post-commit');
    writeFileSync(hook, '#!/usr/bin/env python3\nprint("hi")\n');
    const plan = installer.plan(dir, true);
    expect(plan.changes).toEqual([]);
    expect(plan.skipped[0]?.reason).toContain(BLOCK_COMMAND);
  });

  it('warns when a hook manager owns the hook (husky 4, lefthook, pre-commit)', () => {
    for (const marker of ['# husky > post-commit', 'call_lefthook run', '# File generated by pre-commit: https://pre-commit.com']) {
      const dir = repo();
      writeFileSync(join(dir, '.git', 'hooks', 'post-commit'), `#!/bin/sh\n${marker}\n`);
      expect(installer.plan(dir, true).warnings.join()).toMatch(/managed by/);
    }
  });

  it('removes its block, and the file when nothing else is left', () => {
    const dir = repo();
    const hook = join(dir, '.git', 'hooks', 'post-commit');
    apply(installer.plan(dir, true));
    apply(installer.plan(dir, false));
    expect(existsSync(hook)).toBe(false);

    writeFileSync(hook, '#!/bin/sh\n./notify.sh\n');
    apply(installer.plan(dir, true));
    apply(installer.plan(dir, false));
    expect(readFileSync(hook, 'utf8')).toBe('#!/bin/sh\n./notify.sh\n');
    expect(installer.installed(dir)).toBe(false);
  });

  it('only warns outside git', () => {
    expect(installer.plan(tempDir(), true).warnings).toEqual(['not a git repository, so --track-commits was skipped']);
    expect(installer.plan(tempDir(), false)).toEqual({ changes: [], skipped: [], warnings: [] });
  });

  it('a commit passes silently without estimetry and does not wait for a slow one', () => {
    const dir = repo();
    apply(installer.plan(dir, true));
    const commit = (path: string) =>
      spawnSync('git', ['commit', '-q', '--allow-empty', '-m', 'x'], { cwd: dir, encoding: 'utf8', env: { ...process.env, PATH: path } });

    const gitDir = (execFileSync('which', ['git'], { encoding: 'utf8' }).trim().match(/^(.*)\/[^/]+$/) ?? [])[1] ?? '/usr/bin';
    const without = commit(`${gitDir}:/bin`);
    expect(without.status).toBe(0);
    expect(without.stdout + without.stderr).toBe('');

    const bin = tempDir('bin-');
    const slow = join(bin, 'estimetry');
    writeFileSync(slow, '#!/bin/sh\nsleep 3\n');
    chmodSync(slow, 0o755);
    const started = Date.now();
    const withSlow = commit(`${bin}:${gitDir}:/bin`);
    expect(withSlow.status).toBe(0);
    expect(Date.now() - started).toBeLessThan(2000);
  });
});

describe('NodeProjectFiles', () => {
  it('finds manifests two levels deep, skipping dependencies, examples, hidden dirs and symlinks', () => {
    const root = tempDir();
    for (const dir of ['packages/app', 'node_modules/x', 'examples/demo', '.hidden', 'a/b/c']) {
      mkdirSync(join(root, dir), { recursive: true });
      writeFileSync(join(root, dir, 'package.json'), '{}');
    }
    writeFileSync(join(root, 'package.json'), '{}');
    execFileSync('ln', ['-s', join(root, 'packages'), join(root, 'linked')]);
    const found = files.find(root, ['package.json'], { depth: 2, limit: 200 }).map((p) => p.slice(root.length + 1));
    expect(found).toEqual(['package.json', 'packages/app/package.json']);
    expect(files.find(root, ['package.json'], { depth: 2, limit: 1 })).toHaveLength(1);
  });

  it('writes atomically, keeps the mode of a rewritten file and removes an emptied directory', () => {
    const root = tempDir();
    const path = join(root, 'a', 'b', 'hook');
    files.write(path, 'one', { executable: true });
    files.write(path, 'two');
    expect(readFileSync(path, 'utf8')).toBe('two');
    expect(isExecutable(path)).toBe(true);
    writeFileSync(join(root, 'keep'), '');
    files.remove(path);
    expect(existsSync(join(root, 'a'))).toBe(false); // b and then a became empty
    expect(files.read(path)).toBeUndefined();
    expect(files.isDirectory(root)).toBe(true);

    const deep = join(root, 'x', 'y', 'z', 'file');
    files.write(deep, '1');
    files.remove(deep);
    expect(files.isDirectory(join(root, 'x'))).toBe(true); // only two levels go
    expect(existsSync(join(root, 'x', 'y'))).toBe(false);
  });

  describe('run without the user\'s PATH, as from an IDE on macOS', () => {
    /** A stand-in for the entry point: writes what the hook passed to it. */
    function fakeMain(dir: string): { main: string; out: string } {
      const out = join(dir, 'called');
      const main = join(dir, "dir with space's", 'main.js');
      mkdirSync(join(main, '..'), { recursive: true });
      writeFileSync(
        main,
        `const fs = require('node:fs'); fs.writeFileSync(${JSON.stringify(out)}, ` +
          `process.argv.slice(2).join(' ') + ' ' + fs.readFileSync(0, 'utf8') + ' ' + process.env.ESTIMETRY_HOME);`,
      );
      return { main, out };
    }

    it('the personal hook runs node and the entry point it was installed with', async () => {
      const dir = repo();
      execFileSync('git', ['commit', '-q', '--allow-empty', '-m', 'init'], { cwd: dir });
      const { main, out } = fakeMain(tempDir('main-'));
      apply(new GitCommitHookInstaller({ node: process.execPath, main, home: '/data/estimetry' }).plan(dir, true));
      const hook = join(dir, '.git', 'hooks', 'post-commit');
      const sha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: dir, encoding: 'utf8' }).trim();
      // A PATH with git and the shell only: no estimetry, maybe no node.
      const result = spawnSync('/bin/sh', [hook], { cwd: dir, env: { PATH: '/usr/bin:/bin' } });
      expect(result.status).toBe(0);
      for (let i = 0; i < 50 && !existsSync(out); i++) {
        await new Promise((resolve) => setTimeout(resolve, 100));
      }
      expect(readFileSync(out, 'utf8')).toBe(`hook git post-commit ${sha} /data/estimetry`);
    });

    it('prefers estimetry on PATH, so a terminal runs the current one', async () => {
      const dir = repo();
      execFileSync('git', ['commit', '-q', '--allow-empty', '-m', 'init'], { cwd: dir });
      const bin = tempDir('bin-');
      const out = join(bin, 'called');
      writeFileSync(join(bin, 'estimetry'), `#!/bin/sh\necho from-path > ${JSON.stringify(out)}\n`);
      chmodSync(join(bin, 'estimetry'), 0o755);
      apply(new GitCommitHookInstaller({ node: process.execPath, main: '/nowhere/main.js', home: '/data' }).plan(dir, true));
      spawnSync('/bin/sh', [join(dir, '.git', 'hooks', 'post-commit')], { cwd: dir, env: { PATH: `${bin}:/usr/bin:/bin` } });
      for (let i = 0; i < 50 && !existsSync(out); i++) {
        await new Promise((resolve) => setTimeout(resolve, 100));
      }
      expect(readFileSync(out, 'utf8')).toBe('from-path\n');
    });

    it('a husky hook and an absolute core.hooksPath into the repository through a symlink hold no paths of this machine', () => {
      const runner = new GitCommitHookInstaller({ node: '/opt/node', main: '/opt/main.js', home: '/data' });
      const husky = repo();
      mkdirSync(join(husky, '.husky', '_'), { recursive: true });
      execFileSync('git', ['config', 'core.hooksPath', '.husky/_'], { cwd: husky });
      apply(runner.plan(husky, true));
      expect(readFileSync(join(husky, '.husky', 'post-commit'), 'utf8')).not.toContain('/opt/');
      const dir = repo();
      const link = join(tempDir('link-'), 'repo');
      symlinkSync(dir, link, 'dir');
      execFileSync('git', ['config', 'core.hooksPath', join(link, '.githooks')], { cwd: dir });
      apply(runner.plan(dir, true));
      expect(readFileSync(join(dir, '.githooks', 'post-commit'), 'utf8')).not.toContain('/opt/');
    });

    it('a hook the project commits holds no paths of this machine', () => {
      const dir = repo();
      execFileSync('git', ['config', 'core.hooksPath', 'tools/githooks'], { cwd: dir });
      apply(new GitCommitHookInstaller({ node: '/opt/node', main: '/opt/main.js', home: '/data' }).plan(dir, true));
      const text = readFileSync(join(dir, 'tools', 'githooks', 'post-commit'), 'utf8');
      expect(text).not.toContain('/opt/');
      expect(text).toContain(BLOCK_COMMAND);
    });

    it('a worktree gets the paths in the common hooks directory, which is personal', () => {
      const dir = repo();
      execFileSync('git', ['commit', '-q', '--allow-empty', '-m', 'init'], { cwd: dir });
      const worktree = join(tempDir('wt-'), 'feature');
      execFileSync('git', ['worktree', 'add', '-q', worktree], { cwd: dir });
      apply(new GitCommitHookInstaller({ node: '/opt/node', main: '/opt/main.js', home: '/data' }).plan(worktree, true));
      expect(readFileSync(join(dir, '.git', 'hooks', 'post-commit'), 'utf8')).toContain("estimetry_node='/opt/node'");
    });
  });
});
